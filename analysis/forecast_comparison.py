# %% [markdown]
# # Forecast comparison: which source to trust, for which decision
#
# Reproducible from the warehouse: `python analysis/forecast_comparison.py --db warehouse/planning.duckdb --out analysis/forecast_comparison.md`.
# Every number is from synthetic data. Forecasts are scored as they were knowable at decision time (see `int_forecast_frozen`).

# %%
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb


def pct(v, d=1):
    return "–" if v is None else f"{100 * v:.{d}f}%"


def rel(v, d=1):
    return "–" if v is None else f"{100 * v:+.{d}f}%"


def md_table(rows, cols):
    head = "| " + " | ".join(c for c, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(f(r) for _, f in cols) + " |\n" for r in rows)


def build(con) -> str:
    q = lambda s: con.execute(s).fetchall()
    out = ["# Forecast comparison\n",
           "Generated by `analysis/forecast_comparison.py` from the gold marts. Synthetic data; demo results.\n"]

    # %% 1. The level you aggregate to changes the answer
    rows = q("""select level, source, wape, bias from gold.rpt_accuracy
                where window_name='all' and member='All' and horizon_weeks=4
                order by case level when 'total' then 1 when 'market' then 2 else 3 end, source""")
    out.append("## 1. Aggregate and SKU-level evidence pick different sources\n")
    out.append("Four weeks out, matched pairs, target weeks from March 2025.\n")
    out.append(md_table(rows, [("Level", lambda r: r[0]), ("Source", lambda r: r[1]), ("WAPE", lambda r: pct(r[2])), ("Bias", lambda r: rel(r[3]))]))
    out.append("\nSummed over every SKU the sensing model's errors cancel; at the grain stock is committed they do not. "
               "The consensus plan carries SKU-level order knowledge but a steady over-forecast.\n")

    # %% 2. By horizon
    rows = q("""select a.horizon_weeks, s.wape, c.wape, st.wape, ct.wape
                from (select distinct horizon_weeks from gold.rpt_accuracy) a
                join gold.rpt_accuracy s on s.horizon_weeks=a.horizon_weeks and s.window_name='all' and s.member='All' and s.level='sku_market' and s.source='sensing'
                join gold.rpt_accuracy c on c.horizon_weeks=a.horizon_weeks and c.window_name='all' and c.member='All' and c.level='sku_market' and c.source='consensus'
                join gold.rpt_accuracy st on st.horizon_weeks=a.horizon_weeks and st.window_name='all' and st.member='All' and st.level='total' and st.source='sensing'
                join gold.rpt_accuracy ct on ct.horizon_weeks=a.horizon_weeks and ct.window_name='all' and ct.member='All' and ct.level='total' and ct.source='consensus'
                order by 1""")
    out.append("\n## 2. By horizon\n")
    out.append(md_table(rows, [("Weeks out", lambda r: str(r[0])), ("Sensing, SKU", lambda r: pct(r[1])), ("Consensus, SKU", lambda r: pct(r[2])),
                               ("Sensing, summed", lambda r: pct(r[3])), ("Consensus, summed", lambda r: pct(r[4]))]))

    # %% 3. Bias against service
    rows = q("select factor, is_debiased, wape, bias, fill_if_stocked_to_forecast, excess_share from gold.rpt_bias_tradeoff where factor in (0.92, 0.95, 1.0) or is_debiased order by factor")
    out.append("\n## 3. Reducing bias costs service\n")
    out.append("The consensus plan multiplied by a factor, evaluated on the later half of history. The debiased factor is one over one plus the bias measured on the earlier half, so it is out of sample.\n")
    out.append(md_table(rows, [("Factor", lambda r: f"{r[0]:.3f}" + (" (debiased)" if r[1] else "")), ("WAPE", lambda r: pct(r[2])), ("Bias", lambda r: rel(r[3])),
                               ("Fill if stocked to forecast", lambda r: pct(r[4])), ("Excess units", lambda r: pct(r[5]))]))

    # %% 4. Where the better source on average is the wrong one
    rows = q("""select sku, site_id, max(wape_last_8w) filter (where source='consensus'), max(wape_last_8w) filter (where source='sensing'),
                       max(bias_last_8w) filter (where source='consensus'), max(bias_last_8w) filter (where source='sensing')
                from gold.rpt_accuracy_by_sku where sku in ('NV-S210', 'NV-H330') group by 1, 2 order by 1, 2""")
    out.append("\n## 4. Positions where demand changed\n")
    out.append("Last eight scored weeks, four weeks out. NV-S210 fell in August; the consensus plan did not follow. The NV-H330 rise at Site Gamma is too recent to show at four weeks out, so the inventory page uses year-on-year actuals as the evidence.\n")
    out.append(md_table(rows, [("SKU", lambda r: r[0]), ("Site", lambda r: r[1]), ("WAPE, plan", lambda r: pct(r[2])), ("WAPE, sensing", lambda r: pct(r[3])),
                               ("Bias, plan", lambda r: rel(r[4])), ("Bias, sensing", lambda r: rel(r[5]))]))

    # %% 5. Leakage
    r = q("select snapshot_week, naive_created_at, pairs_affected, wape_naive, wape_asof from gold.rpt_leak_audit")[0]
    out.append(f"\n## 5. The leaked backfill\n\nConsensus snapshot {r[0]} was republished on {r[1]:%Y-%m-%d} with actuals in hand. "
               f"A latest-version model would score it at {pct(r[3])} WAPE on {r[2]} pairs; the version planners saw scores {pct(r[4])}. "
               "The as-of rule excludes it, and a dbt test fails the build if any scored forecast was created after its target week began.\n")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="warehouse/planning.duckdb")
    ap.add_argument("--out", default="analysis/forecast_comparison.md")
    a = ap.parse_args()
    with duckdb.connect(a.db, read_only=True) as con:
        Path(a.out).write_text(build(con), encoding="utf-8", newline="\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
